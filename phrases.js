/* ─── Заголовки сторис ────────────────────────────────────────────
   «Записываю на приём» — так пишут в регистратуре поликлиники, а не
   мастер своим подписчикам. И главное: одна и та же фраза из недели в
   неделю приедается тем, кто на мастера подписан, — а подписчики у
   него одни и те же, в отличие от клиентов.

   Поэтому фраза не одна, а набор, и подбирается он под обстановку:
   сколько окон осталось, на какой день, какой формат. Мастеру в
   кабинете показываем несколько вариантов на выбор — это и есть то,
   чем мы полезнее генератора картинок.

   Главное правило: **пустотой не торгуем**. В красоте свободный
   календарь — антиреклама: «много свободного времени» читается как
   «к нему никто не ходит», и чем честнее цифра, тем хуже. Поэтому
   количество окон называем только когда их мало — дефицит продаёт, —
   а на свободном дне говорим про выбор и приглашение, ни словом не
   упоминая, сколько там места. То же правило уже действует в отборе
   окон: день, свободный больше чем на 60%, показывает меньше слотов.

   Правила, которым подчиняется каждая строка:
     • без глаголов с родом: «открыта запись», а не «открыла» — мастер
       бывает и мужчиной, и салоном;
     • без эмодзи — они в интерфейсе запрещены и на картинке тоже;
     • коротко: заголовок встаёт в две строки крупным кеглем, длинная
       фраза заставляет его мельчать;
     • грамматика правильная: это публичная картинка, а не переписка. */

const plural = (n, one, few, many) => {
  const a = Math.abs(n) % 100, b = a % 10;
  if (a > 10 && a < 20) return many;
  if (b > 1 && b < 5) return few;
  return b === 1 ? one : many;
};

/* {день} — «сегодня», «завтра» или «понедельник»: все три одинаково
   ложатся в «на {день}». {n} — число окон, {окон} — его форма.

   {День} с большой буквы — шаблон, которому нужно существительное:
   «Понедельник почти весь свободен» читается, «Сегодня почти весь
   свободен» — нет, это наречие. Такие строки отбрасываем, когда день
   назван словом «сегодня» или «завтра». */
/* Мало окон — единственный случай, когда цифру называть выгодно:
   это дефицит, и он подгоняет. */
const SLOTS_FEW = [
  "Осталось {n} {окон} на {день}",
  "Есть {n} {окон} на {день}",
  "На {день} ещё можно успеть",
  "Последние окошки на {день}",
];
/* Обычный день: говорим про выбор, без чисел. */
const SLOTS_SOME = [
  "Свободные окошки на {день}",
  "Выбирайте время на {день}",
  "Свободное время на {день}",
  "Записываю на {день}",
];
/* Свободный день: приглашение и удобство. Ни «много», ни «весь
   свободен», ни любого другого намёка на то, что к мастеру не идут. */
const SLOTS_OPEN = [
  "Открыта запись на {день}",
  "Подберём удобное время на {день}",
  "Есть удобное время на {день}",
  "Записываю на {день}",
];
const WEEK = [
  "Свободное время на неделю",
  "Выбирайте удобный день",
  "Окошки на этой неделе",
  "Вся неделя перед вами",
];
const HOT = [
  "Освободилось окно",
  "Окно на {день}",
  "Кто-то отменился",
  "Внезапно свободно",
];
const REVIEW = [
  "Спасибо за отзыв",
  "Такие отзывы греют",
  "Приятно читать",
  "Спасибо, что доверяете",
];

/* Единицу в заголовке пишем словом: «Осталось одно окно» — это
   строка на плакате, а не счётчик. Дальше цифра читается лучше слова. */
const numWord = (n) => (n === 1 ? "одно" : String(n));

const fill = (tpl, { day = "", free = 0 }) => tpl
  .replace(/\{день\}/g, day)
  .replace(/\{n\}/g, numWord(free))
  .replace(/\{окон\}/g, plural(free, "окно", "окна", "окон"));

/* Набор под обстановку. Порядок перемешиваем, но не случайно до конца:
   первым идёт тот, что лучше всего описывает именно этот день, иначе
   «осталось одно окно» могло бы выпасть на полупустой день. */
const poolFor = ({ format, free = 0, open = false }) => {
  if (format === "review") return REVIEW;
  if (format === "week") return WEEK;
  if (format === "hot") return HOT;
  if (open || free >= 9) return SLOTS_OPEN;
  if (free <= 3) return SLOTS_FEW;
  return SLOTS_SOME;
};

const shuffle = (arr, rnd = Math.random) => {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
};

/* Что предложить мастеру: сначала подходящие по обстановке, затем
   соседний набор — чтобы список не кончался после четырёх нажатий. */
const suggestTitles = (ctx = {}, rnd = Math.random) => {
  /* Все шаблоны построены на «на {день}»: он одинаково ложится и на
     «сегодня», и на «понедельник». Конструкций, которым нужно
     существительное («Понедельник почти весь свободен»), больше нет —
     они и грамматику усложняли, и торговали пустотой. */
  const pool = poolFor(ctx);
  const main = pool;
  /* Запас берём только нейтральный. Смешивать «последние окошки» со
     свободным днём нельзя: на дне с четырнадцатью окнами это враньё,
     а картинка публичная. */
  const extra = ctx.format === "slots" && pool !== SLOTS_SOME ? SLOTS_SOME : [];
  const seen = new Set();
  return [...shuffle(main, rnd), ...shuffle(extra, rnd)]
    .map((t) => fill(t, ctx))
    .filter((t) => (seen.has(t) ? false : seen.add(t)));
};

/* Заголовок по умолчанию: тоже из набора, а не одна строка навсегда.
   Мастер, который ничего не выбрал, всё равно получает разные фразы. */
const defaultTitle = (ctx = {}, rnd = Math.random) => suggestTitles(ctx, rnd)[0] || "";

module.exports = { suggestTitles, defaultTitle, poolFor, fill };
